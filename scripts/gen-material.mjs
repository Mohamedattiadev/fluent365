// Generates Material 3 design tokens and icon paths for the pocket app (run once after changing seeds/icons):
//   pnpm gen:material   (bundles this file with esbuild first: the colour package uses extensionless ESM imports)
// Colours: @material/material-color-utilities (Apache-2.0), "tonal spot" schemes like Android's Material You.
// Icons: Material Symbols Rounded, weight 400 (@material-symbols/svg-400, Apache-2.0).
// Output: apps/pocket/src/theme.gen.css and apps/pocket/src/components/icons.gen.ts (both committed).
import { argbFromHex, hexFromArgb, Hct, MaterialDynamicColors as M, SchemeTonalSpot, TonalPalette } from "@material/material-color-utilities";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname;

// Colour themes the learner can pick in Settings (Android calls this "wallpaper colours").
export const SEEDS = { violet: "#6750A4", blue: "#1A73E8", green: "#386A20", orange: "#B25E02" };
// One fixed hue per skill, used for the round icon badges and thin accents.
const SKILLS = { words: "#7E57C2", grammar: "#1E6FD9", reading: "#00897B", listening: "#C28A00", writing: "#E2571E", speaking: "#D81B60" };

const ROLES = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer", "error", "onError", "errorContainer", "onErrorContainer",
  "surface", "onSurface", "onSurfaceVariant", "surfaceDim", "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
  "surfaceContainerHigh", "surfaceContainerHighest", "outline", "outlineVariant", "inverseSurface", "inverseOnSurface", "inversePrimary", "scrim"];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function scheme(hex, dark, contrast = 0) {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), dark, contrast);
  return ROLES.map((r) => {
    const dc = typeof M[r] === "function" ? M[r]() : M[r] ?? new M()[r]?.();
    return `--md-${kebab(r)}: ${hexFromArgb(dc.getArgb(s))};`;
  }).join(" ");
}
// Material has no "success" role; correct answers use a green tonal palette built the same way.
function success(dark) {
  const p = TonalPalette.fromInt(argbFromHex("#2E7D32"));
  const [c, cont, on] = dark ? [80, 30, 90] : [40, 90, 10];
  return `--md-success: ${hexFromArgb(p.tone(c))}; --md-success-container: ${hexFromArgb(p.tone(cont))}; --md-on-success-container: ${hexFromArgb(p.tone(on))};`;
}
function skills(dark) {
  return Object.entries(SKILLS).map(([k, hex]) => {
    const p = TonalPalette.fromInt(argbFromHex(hex));
    const [ink, cont, on] = dark ? [80, 30, 90] : [40, 90, 10];
    return `--sk-${k}: ${hexFromArgb(p.tone(ink))}; --sk-${k}-container: ${hexFromArgb(p.tone(cont))}; --sk-${k}-on: ${hexFromArgb(p.tone(on))};`;
  }).join(" ");
}

let css = "/* Generated by scripts/gen-material.mjs. Do not edit by hand. */\n";
for (const [name, hex] of Object.entries(SEEDS)) {
  const light = `:root[data-seed="${name}"]`;
  css += `${light} { ${scheme(hex, false)} }\n`;
  css += `${light}[data-contrast="high"] { ${scheme(hex, false, 1)} }\n`;
  css += `@media (prefers-color-scheme: dark) { ${light}:not([data-theme="light"]) { ${scheme(hex, true)} } ${light}:not([data-theme="light"])[data-contrast="high"] { ${scheme(hex, true, 1)} } }\n`;
  css += `${light}[data-theme="dark"] { ${scheme(hex, true)} }\n`;
  css += `${light}[data-theme="dark"][data-contrast="high"] { ${scheme(hex, true, 1)} }\n`;
}
css += `:root { ${skills(false)} ${success(false)} }\n`;
css += `@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { ${skills(true)} ${success(true)} } }\n`;
css += `:root[data-theme="dark"] { ${skills(true)} ${success(true)} }\n`;
css += `/* Swatches for the colour picker in Settings. */\n:root { ${Object.entries(SEEDS).map(([k, v]) => `--seed-${k}: ${v};`).join(" ")} }\n`;
writeFileSync(join(root, "apps/pocket/src/theme.gen.css"), css);

// ---------- Icons ----------
const ICONS = {
  today: "today", words: "style", grammar: "spellcheck", reading: "menu_book", listening: "headphones", writing: "edit_note", speaking: "mic",
  mic: "mic", practice: "exercise", progress: "monitoring", settings: "settings", check: "check", done: "check_circle", x: "close", close: "close",
  hint: "lightbulb", audio: "volume_up", timer: "timer", rest: "bedtime", play: "play_arrow", pause: "pause", stop: "stop", arrow: "arrow_forward",
  back: "arrow_back", chevron: "chevron_right", warn: "warning", again: "replay", upload: "upload", file: "description", download: "download", info: "info",
  list: "checklist", school: "school", fire: "local_fire_department", flag: "flag", bolt: "bolt", star: "star", palette: "palette", text: "format_size",
  contrast: "contrast", motion: "animation", person: "person", language: "translate", schedule: "schedule", delete: "delete", dark: "dark_mode",
};
const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve("@material-symbols/svg-400/package.json")), "rounded");
const pathOf = (file) => [...readFileSync(join(dir, file), "utf8").matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
const out = Object.fromEntries(Object.entries(ICONS).map(([k, sym]) => [k, { d: pathOf(`${sym}.svg`), f: pathOf(`${sym}-fill.svg`) }]));
writeFileSync(join(root, "apps/pocket/src/components/icons.gen.ts"),
  `// Generated by scripts/gen-material.mjs from Material Symbols Rounded (Apache-2.0). Do not edit by hand.\n// viewBox "0 -960 960 960"; d = outlined, f = filled (used for the selected navigation item).\nexport const ICON_PATHS: Record<string, { d: string; f: string }> = ${JSON.stringify(out, null, 0)};\n`);
console.log("theme.gen.css and icons.gen.ts written");
